"""AT-01 / AT-03 / AT-23(backend): HTTP-driven Ego pipeline and platform health.

These tests use the public API only (plus the in-process task runner, which is
the same engine the workers use) so they exercise the real request/response
contracts, RBAC, idempotency and the object-store flow.
"""

from __future__ import annotations

import hashlib
import json
import uuid
from pathlib import Path
from urllib.parse import urlparse

import pytest

pytestmark = pytest.mark.e2e

FIXTURES = Path("fixtures")


def _upload(client, put_url: str, data: bytes) -> None:
    parsed = urlparse(put_url)
    response = client.put(parsed.path + ("?" + parsed.query if parsed.query else ""), content=data)
    assert response.status_code == 200, response.text


def _import_via_http(client, operator_headers, path: Path, *, source_type: str, filename: str, mapping=None):
    data = path.read_bytes()
    payload = {
        "source_type": source_type,
        "filename": filename,
        "size_bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
        "data_origin": "synthetic",
        "license": "synthetic fixture generated by this repository",
        "mapping": mapping or {},
    }
    initiated = client.post("/api/v1/imports/initiate", json=payload, headers=operator_headers)
    assert initiated.status_code == 201, initiated.text
    body = initiated.json()["data"]
    _upload(client, body["put_url"], data)
    completed = client.post(
        f"/api/v1/imports/{body['import_id']}/complete",
        headers={**operator_headers, "Idempotency-Key": str(uuid.uuid4())},
    )
    assert completed.status_code == 202, completed.text
    return body["import_id"], completed.json()["data"]["import_job_id"]


def _run_tasks(session_factory):
    from embodied_dataops.workflow.runner import run_until_idle

    counts = run_until_idle(session_factory, pools=("cpu", "vision", "ros2"), max_iterations=200)
    assert counts["failed"] == 0, counts
    return counts


