def test_ten_fixtures_are_generated():
    manifest = FIXTURES / "manifest.json"
    if not manifest.is_file():
        pytest.skip("fixtures/manifest.json missing; run `make seed-synthetic`")
    payload = json.loads(manifest.read_text(encoding="utf-8"))
    ids = {fixture["fixture_id"] for fixture in payload["fixtures"]}
    expected = {
        "F01_good_lerobot",
        "F02_bad_timestamps",
        "F03_bad_dims",
        "F04_ego_video",
        "F05_mcap_good",
        "F06_mcap_gap",
        "F07_corrupt_mp4",
        "F08_bad_tar",
        "F09_fake_eval",
        "F10_blurry_video",
    }
    assert expected.issubset(ids), f"missing fixtures: {sorted(expected - ids)}"
    assert payload.get("data_origin") == "synthetic"


def test_ego_mp4_http_pipeline(client, operator_headers, reviewer_headers, session_factory):
    video = FIXTURES / "generate" / "F04_ego_video.mp4"
    if not video.is_file():
        pytest.skip("F04 fixture missing; run `make seed-synthetic`")
    import_id, job_id = _import_via_http(
        client, operator_headers, video, source_type="EGO_MP4", filename="F04_ego_video.mp4"
    )
    counts = _run_tasks(session_factory)
    assert counts["succeeded"] >= 5

    detail = client.get(f"/api/v1/imports/{import_id}", headers=operator_headers).json()["data"]
    assert detail["job"]["id"] == job_id and detail["job"]["state"] == "SUCCEEDED"
    episodes = client.get("/api/v1/episodes", headers=operator_headers).json()["data"]
    ego = [episode for episode in episodes if episode["episode_type"] == "ego_video_episode"]
    assert len(ego) == 1, episodes
    episode = ego[0]
    assert episode["sample_count"] == 100
    assert episode["duration_ns"] >= 9_900_000_000
    assert episode["quality_status"] == "PASS"
    assert episode["status"] == "READY_FOR_REVIEW"

    # no synthetic state/action for ego episodes
    samples = client.get(
        f"/api/v1/episodes/{episode['id']}/samples?limit=100", headers=operator_headers
    ).json()["data"]["samples"]
    assert len(samples) == 100
    assert samples[0]["t_ns"] == 0
    assert samples[-1]["t_ns"] == 9_900_000_000
    assert all("state" not in row and "action" not in row for row in samples)

    quality = client.get(f"/api/v1/episodes/{episode['id']}/quality", headers=operator_headers)
    assert quality.status_code == 200
    quality_body = quality.json()["data"]
    assert quality_body["verdict"] == "PASS"
    assert quality_body["metrics"]["valid_sample_count"] == 100

    preview = client.get(f"/api/v1/episodes/{episode['id']}/preview", headers=operator_headers)
    assert preview.status_code == 200
    assert preview.json()["data"]["video_url"]

    annotations = client.get(
        f"/api/v1/episodes/{episode['id']}/annotations", headers=operator_headers
    )
    assert annotations.status_code == 200
    annotation_body = annotations.json()["data"]
    annotation_set = annotation_body["annotation_set"]
    annotation_set_id = annotation_set.get("annotation_set_id") or annotation_set.get("id")
    assert annotation_set_id, annotation_set
    assert annotation_set["status"] == "PENDING_REVIEW"
    assert annotation_body["frames"], "annotation candidate frames must be returned"

    # operator cannot review (403); reviewer can, exactly once
    forbidden = client.post(
        f"/api/v1/annotation-sets/{annotation_set_id}/reviews",
        json={"decision": "APPROVED", "note": ""},
        headers=operator_headers,
    )
    assert forbidden.status_code == 403
    reviewed = client.post(
        f"/api/v1/annotation-sets/{annotation_set_id}/reviews",
        json={"decision": "APPROVED", "note": "reviewed overlay; ego video is not used for robot action supervision"},
        headers=reviewer_headers,
    )
    assert reviewed.status_code == 201, reviewed.text
    assert reviewed.json()["data"]["new_status"] == "APPROVED"
    duplicate = client.post(
        f"/api/v1/annotation-sets/{annotation_set_id}/reviews",
        json={"decision": "REJECTED", "note": ""},
        headers=reviewer_headers,
    )
    assert duplicate.status_code == 409
