def test_episode_data_origin_maps_to_the_agent_vocabulary(client, viewer_headers, session_factory):
    with session_factory() as session:
        synthetic = new_episode(session, index=0, data_origin="synthetic")
        public = new_episode(session, index=1, data_origin="public_dataset")
        robot = new_episode(session, index=2, data_origin="robot_capture")
        session.commit()
        ids = {"synthetic": synthetic.id, "public": public.id, "robot": robot.id}
    assert (
        client.get(f"/api/v1/episodes/{ids['synthetic']}", headers=viewer_headers)
        .json()["data"]["episode"]["data_origin"]
        == "synthetic"
    )
    assert (
        client.get(f"/api/v1/episodes/{ids['public']}", headers=viewer_headers)
        .json()["data"]["episode"]["data_origin"]
        == "public_dataset"
    )
    assert (
        client.get(f"/api/v1/episodes/{ids['robot']}", headers=viewer_headers)
        .json()["data"]["episode"]["data_origin"]
        == "unknown"
    )


