# Fixed 202 shapes (C3)
# ---------------------------------------------------------------------------
def test_three_conditional_writes_return_the_fixed_202_shape(client, operator_headers, session_factory):
    with session_factory() as session:
        episode = new_episode(session)
        session.commit()
        episode_id = episode.id
    run_response = client.post(
        f"/api/v1/episodes/{episode_id}/pipeline-runs",
        json={"pipeline_version": "2.0.0"},
        headers={**operator_headers, "If-Match": '"episode-rev:1"', "Idempotency-Key": str(uuid.uuid4())},
    )
    assert run_response.status_code == 202, run_response.text
    assert set(run_response.json()["data"]) == {"operation_id", "new_run_id", "state", "effect_state"}
    assert run_response.json()["data"]["state"] == "QUEUED"
    assert run_response.json()["data"]["effect_state"] == "COMMITTED"

    with session_factory() as session:
        _, run, task = new_failed_task(session)
        task_id, expected_run_id = task.id, run.id
        session.commit()
    retry_response = client.post(
        f"/api/v1/tasks/{task_id}/retry",
        json={"expected_run_id": expected_run_id},
        headers={**operator_headers, "If-Match": '"task-rev:1"', "Idempotency-Key": str(uuid.uuid4())},
    )
    assert retry_response.status_code == 202, retry_response.text
    assert set(retry_response.json()["data"]) == {
        "operation_id",
        "new_run_id",
        "state",
        "effect_state",
    }

    with session_factory() as session:
        evaluation = new_evaluation(session)
        session.commit()
        evaluation_id = evaluation.id
    gap_response = client.post(
        f"/api/v1/evaluations/{evaluation_id}/analyze-gaps",
        json={"success_rate_threshold": 0.8, "min_trials": 20},
        headers={
            **operator_headers,
            "If-Match": '"evaluation-rev:1"',
            "Idempotency-Key": str(uuid.uuid4()),
        },
    )
    assert gap_response.status_code == 202, gap_response.text
    assert set(gap_response.json()["data"]) == {
        "operation_id",
        "analysis_id",
        "state",
        "effect_state",
    }


