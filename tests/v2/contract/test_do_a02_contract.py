def test_do_a01_evaluation_read_model(client, viewer_headers, session_factory):
    with session_factory() as session:
        evaluation = new_evaluation(session)
        session.commit()
        evaluation_id = evaluation.id
    response = client.get(f"/api/v1/evaluations/{evaluation_id}", headers=viewer_headers)
    assert response.status_code == 200, response.text
    data = response.json()["data"]
    assert {
        "evaluation_id",
        "dataset_version_id",
        "schema_version",
        "model_id",
        "is_simulated",
        "results",
        "created_at",
        "business_revision",
        "results_sha256",
    } <= set(data)
    assert data["evaluation_id"] == evaluation_id
    assert data["schema_version"] == "evaluation/1.0"
    assert data["model_id"] == "sim-policy-v1"
    assert data["is_simulated"] is True
    keys = [result["scenario_key"] for result in data["results"]]
    assert keys == sorted(keys), "DO-A01 requires results sorted by scenario_key"
    for result in data["results"]:
        assert set(result) == {"scenario_key", "trials", "successes"}
        assert 0 <= result["successes"] <= result["trials"] <= 100_000
    assert len(data["results_sha256"]) == 64
    assert data["business_revision"] == 1


