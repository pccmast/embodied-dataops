# Runtime OpenAPI + capabilities
# ---------------------------------------------------------------------------
def test_runtime_openapi_declares_the_contract(client, viewer_headers):
    schema = client.get("/openapi.json").json()
    assert schema["openapi"].startswith("3.1")
    assert schema["x-contract-version"] == "do-agent-contract/2.0.0" == CONTRACT_VERSION
    paths = schema["paths"]
    for path, methods in REQUIRED_PATHS.items():
        assert path in paths, f"missing OpenAPI path {path}"
        for method in methods:
            assert method in paths[path], f"missing {method.upper()} {path}"

    # Conditional-write operations must document both headers.
    for path in CONDITIONAL_WRITES:
        parameters = schema["paths"][path]["post"].get("parameters", [])
        names = {(parameter.get("in"), parameter.get("name")) for parameter in parameters}
        assert ("header", "If-Match") in names, f"{path} must document If-Match"
        assert ("header", "Idempotency-Key") in names, f"{path} must document Idempotency-Key"

    # The capabilities probe must advertise the same contract version.
    capabilities = client.get("/api/v1/capabilities", headers=viewer_headers).json()["data"]
    assert capabilities["contract_version"] == schema["x-contract-version"]


def test_committed_openapi_v2_artifact_matches_runtime(client):
    """``dataops openapi-v2`` output is the committed cross-project artifact."""
    assert OPENAPI_V2.is_file(), (
        "docs/api-openapi-v2.json is missing; regenerate with `dataops openapi-v2`"
    )
    committed = json.loads(OPENAPI_V2.read_text(encoding="utf-8"))
    runtime = client.get("/openapi.json").json()
    assert committed.get("x-contract-version") == runtime.get("x-contract-version")
    for path in REQUIRED_PATHS:
        assert path in committed["paths"], f"committed OpenAPI v2 misses {path}"


