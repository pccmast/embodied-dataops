def test_error_envelope_shape_for_contract_errors(client, operator_headers, session_factory):
    with session_factory() as session:
        episode = new_episode(session)
        session.commit()
        episode_id = episode.id
    path = f"/api/v1/episodes/{episode_id}/pipeline-runs"
    body = {"pipeline_version": "2.0.0"}
    for headers, status, code in (
        ({**operator_headers, "Idempotency-Key": str(uuid.uuid4())}, 428, "PRECONDITION_REQUIRED"),
        (
            {
                **operator_headers,
                "Idempotency-Key": str(uuid.uuid4()),
                "If-Match": '"episode-rev:99"',
            },
            412,
            "PRECONDITION_FAILED",
        ),
    ):
        response = client.post(path, json=body, headers=headers)
        payload = _error(response, status, code)
        assert set(payload) == {"error", "request_id"}
        assert set(payload["error"]) == {"code", "message", "details"}
        assert payload["request_id"]
