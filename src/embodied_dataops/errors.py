class ApiError(Exception):
    """Business error surfaced through the uniform JSON error envelope."""

    def __init__(
        self,
        code: ErrorCode,
        message: str,
        *,
        status_code: int | None = None,
        details: dict[str, Any] | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.status_code = status_code or _HTTP_STATUS.get(code, 400)
        self.details = details or {}

    def to_dict(self) -> dict[str, Any]:
        return {"code": self.code.value, "message": self.message, "details": self.details}


class RetryableError(Exception):
    """Raised by task handlers for transient failures (SPEC 6.2 retryable set)."""

    def __init__(self, code: ErrorCode, message: str, *, details: dict[str, Any] | None = None) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.details = details or {}


class TerminalTaskError(Exception):
    """Raised by task handlers for non-retryable failures."""

    def __init__(self, code: ErrorCode, message: str, *, details: dict[str, Any] | None = None) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.details = details or {}


class CancelledError(Exception):
    """Cooperative cancellation requested by the API; the worker stops cleanly."""
