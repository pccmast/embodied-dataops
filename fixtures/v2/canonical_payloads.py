def _ros2_cdr():
    import sys

    repository_root = str(Path(__file__).resolve().parents[2])
    if repository_root not in sys.path:
        sys.path.insert(0, repository_root)
    from services.ros2_adapter import cdr  # type: ignore[import-not-found]

    return cdr


def _mcap_writer(stream):
    from mcap.writer import Writer

    writer = Writer(stream)
    try:
        writer.start(profile="ros2", library="embodied-dataops-v2-fixtures")
    except TypeError:  # pragma: no cover - older mcap writer signature
        writer.start()
    return writer


def _register_channels(writer: Any, channels: OrderedDict[str, tuple[str, str]]) -> dict[str, int]:
    identifiers: dict[str, int] = {}
    for key, (topic, message_type) in channels.items():
        if message_type == MCAP_POINTCLOUD_TYPE:
            definition = POINTCLOUD_DEFINITION
        elif message_type == MCAP_LOG_TYPE:
            definition = "string level\nstring name\nstring msg\n"
        else:
            definition = _ros2_cdr().ROS2_MSG_DEFINITIONS[message_type]
        schema_id = writer.register_schema(
            name=message_type, encoding="ros2msg", data=definition.encode("utf-8")
        )
        identifiers[key] = writer.register_channel(
            topic=topic, message_encoding="cdr", schema_id=schema_id
        )
    return identifiers


def _mcap_messages(
    *,
    profile: Any,
    duration_s: float,
    rates: dict[str, int],
    with_wrist: bool,
    with_pointcloud: bool,
    with_unknown_topic: bool,
    case: str,
) -> tuple[list[tuple[int, str, bytes]], dict[str, int]]:
    cdr = _ros2_cdr()
    duration_ns = int(duration_s * 1_000_000_000)

    def times(rate: int) -> list[int]:
        interval = 1_000_000_000 // rate
        return [MCAP_BASE_NS + index * interval for index in range(int(duration_ns // interval) + 1)]

    front_times = times(rates["front"])
    wrist_times = times(rates["wrist"]) if with_wrist else []
    state_times = times(rates["state"])
    action_times = times(rates["action"])
    if case == "invalid":
        # camera frame gap: 0.9 s .. 1.2 s
        front_times = [
            value
            for value in front_times
            if not (MCAP_BASE_NS + 900_000_000 <= value < MCAP_BASE_NS + 1_200_000_000)
        ]
        # joint-state gap: 0.4 s .. 0.6 s
        state_times = [
            value
            for value in state_times
            if not (MCAP_BASE_NS + 400_000_000 <= value < MCAP_BASE_NS + 600_000_000)
        ]
        # action stream starts 0.2 s late
        action_times = [value for value in action_times if value >= MCAP_BASE_NS + 200_000_000]
    messages: list[tuple[int, str, bytes]] = []
    header_offset = 2_000_000
    for index, log_time in enumerate(front_times):
        frame = _camera_frame(index, SEED, width=MCAP_IMAGE_WIDTH, height=MCAP_IMAGE_HEIGHT)
        messages.append(
            (
                log_time,
                "front",
                cdr.encode_image(
                    width=frame.shape[1],
                    height=frame.shape[0],
                    encoding="rgb8",
                    data=frame.tobytes(),
                    header_stamp_ns=log_time + header_offset,
                    frame_id="camera_front",
                ),
            )
        )
    for index, log_time in enumerate(wrist_times):
        frame = _camera_frame(
            index, SEED + 500, width=MCAP_IMAGE_WIDTH, height=MCAP_IMAGE_HEIGHT
        )
        messages.append(
            (
                log_time,
                "wrist",
                cdr.encode_image(
                    width=frame.shape[1],
                    height=frame.shape[0],
                    encoding="rgb8",
                    data=frame.tobytes(),
                    header_stamp_ns=log_time + header_offset,
                    frame_id="camera_wrist",
                ),
            )
        )
    for index, log_time in enumerate(state_times):
        state = _joint_state(index, profile.state_dim, seed_offset=SEED % 89)
        messages.append(
            (
                log_time,
                "state",
                cdr.encode_joint_state(
                    names=list(profile.joint_names),
                    position=[float(value) for value in state],
                    header_stamp_ns=log_time + header_offset,
                    frame_id="base_link",
                ),
            )
        )
    for index, log_time in enumerate(action_times):
        state = _joint_state(index, profile.action_dim, seed_offset=SEED % 89)
        action = _robot_action(state)
        messages.append(
            (
                log_time,
                "action",
                cdr.encode_float64_multi_array(data=[float(value) for value in action]),
            )
        )
    if with_pointcloud:
        pointcloud_times = times(5)
        for log_time in pointcloud_times:
            messages.append((log_time, "points", b"\x00" * 32))
    if with_unknown_topic:
        for index in range(3):
            messages.append(
                (
                    MCAP_BASE_NS + index * 100_000_000,
                    "unknown",
                    ("synthetic diagnostics message %d" % index).encode("utf-8"),
                )
            )
    messages.sort(key=lambda item: (item[0], item[1]))
    counts = {key: 0 for key in ("front", "wrist", "state", "action", "points", "unknown")}
    for _log_time, key, _data in messages:
        counts[key] += 1
    return messages, counts


def generate_mcap_fixture(
    path: Path | str,
    *,
    profile: Any,
    duration_s: float = 1.6,
    rates: dict[str, int] | None = None,
    with_wrist: bool = True,
    with_pointcloud: bool = False,
    with_unknown_topic: bool = False,
    case: str = "good",
) -> Path:
    """Generate one deterministic ROS 2 CDR MCAP v2 fixture."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    rates = dict(rates or {"front": 30, "wrist": 15, "state": 100, "action": 50})
    channels: OrderedDict[str, tuple[str, str]] = OrderedDict()
    if case == "unsupported":
        # deliberately wrong schema on the front-camera topic
        channels["front"] = (TOPIC_FRONT, MCAP_JOINT_STATE_TYPE)
    else:
        channels["front"] = (TOPIC_FRONT, MCAP_IMAGE_TYPE)
    if with_wrist:
        channels["wrist"] = (TOPIC_WRIST, MCAP_IMAGE_TYPE)
    channels["state"] = (TOPIC_JOINT_STATES, MCAP_JOINT_STATE_TYPE)
    channels["action"] = (TOPIC_ACTION, MCAP_ACTION_TYPE)
    if with_pointcloud:
        channels["points"] = (TOPIC_POINTS, MCAP_POINTCLOUD_TYPE)
    if with_unknown_topic:
        channels["unknown"] = (TOPIC_UNKNOWN, MCAP_LOG_TYPE)
    messages, counts = _mcap_messages(
        profile=profile,
        duration_s=duration_s,
        rates=rates,
        with_wrist=with_wrist,
        with_pointcloud=with_pointcloud,
        with_unknown_topic=with_unknown_topic,
        case=case,
    )
    with path.open("wb") as stream:
        writer = _mcap_writer(stream)
        identifiers = _register_channels(writer, channels)
        for log_time, key, data in messages:
            writer.add_message(
                channel_id=identifiers[key],
                log_time=log_time,
                publish_time=log_time,
                data=data,
            )
        writer.finish()
    sidecar = path.with_suffix(".topics.json")
    sidecar.write_text(
        json.dumps(
            {
                "fixture": path.name,
                "profile_id": profile.profile_id,
                "profile_revision": profile.profile_revision,
                "topics": {key: topic for key, (topic, _type) in channels.items()},
                "message_counts": counts,
                "case": case,
                "seed": SEED,
                "data_origin": "synthetic",
            },
            sort_keys=True,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    return path


