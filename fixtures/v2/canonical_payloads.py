def _pattern_base(width: int, height: int) -> np.ndarray:
    x = np.linspace(0, 255, width, dtype=np.uint8)
    y = np.linspace(0, 255, height, dtype=np.uint8)
    grid = ((x[None, :].astype(np.uint16) + y[:, None].astype(np.uint16)) % 256).astype(np.uint8)
    frame = np.stack([grid, np.flipud(grid), np.rot90(grid, k=2)], axis=2)
    return np.ascontiguousarray(frame)


def _camera_frame(index: int, seed_offset: int, *, width: int, height: int) -> np.ndarray:
    base = _pattern_base(width, height)
    frame = base.copy()
    x = int((index * 5 + seed_offset) % max(1, width - 20))
    y = int((index * 3 + seed_offset) % max(1, height - 20))
    frame[y : y + 18, x : x + 18, :] = (240, 40, 40)
    frame[y + 6 : y + 12, x + 6 : x + 12, :] = (30, 230, 30)
    return frame


def _joint_state(index: int, dim: int, *, seed_offset: int) -> np.ndarray:
    phase = index * 0.15 + seed_offset
    return np.asarray(
        [0.25 * np.sin(phase + axis * 0.3) + 0.01 * axis for axis in range(dim)],
        dtype=np.float64,
    )


def _robot_action(state: np.ndarray) -> np.ndarray:
    return (np.asarray(state, dtype=np.float64) + 0.01).astype(np.float64)


