def _lerobot_features(profile: Any, cameras: dict[str, str]) -> dict[str, Any]:
    features: dict[str, Any] = {
        key: {
            "dtype": "video",
            "shape": (3, VIDEO_HEIGHT, VIDEO_WIDTH),
            "names": ["channels", "height", "width"],
        }
        for key in cameras.values()
    }
    features["observation.state"] = {
        "dtype": "float32",
        "shape": (profile.state_dim,),
        "names": list(profile.joint_names),
    }
    features["action"] = {
        "dtype": "float32",
        "shape": (profile.action_dim,),
        "names": list(profile.joint_names),
    }
    return features


def _writer_image_value(rgb: np.ndarray) -> Any:
    import torch

    chw = np.ascontiguousarray(np.transpose(np.asarray(rgb, dtype=np.uint8), (2, 0, 1)))
    return torch.from_numpy(chw)


def _create_lerobot_dataset(dataset_class: Any, *, root: Path, repo_id: str, features: dict[str, Any]) -> Any:
    kwargs: dict[str, Any] = {
        "repo_id": repo_id,
        "fps": LEROBOT_FPS,
        "features": features,
        "root": str(root),
        "robot_type": repo_id.split("/")[-1],
        "use_videos": True,
        "image_writer_threads": 0,
        "image_writer_processes": 0,
    }
    try:
        parameters = inspect.signature(dataset_class.create).parameters
    except (TypeError, ValueError):  # pragma: no cover
        parameters = {}
    if "video_backend" in parameters:
        try:
            import av  # noqa: F401

            kwargs["video_backend"] = "pyav"
        except Exception:
            pass
    filtered = {
        key: value
        for key, value in kwargs.items()
        if not parameters or key in parameters
    }
    return dataset_class.create(**filtered)


def _save_episode(dataset: Any, task: str) -> None:
    try:
        parameters = inspect.signature(dataset.save_episode).parameters
    except (TypeError, ValueError):  # pragma: no cover
        parameters = {}
    if "episode_data" in parameters and "parallel_encoding" in parameters:
        dataset.save_episode(None, parallel_encoding=False)
        return
    try:
        dataset.save_episode(task=task)
        return
    except TypeError:
        pass
    try:
        dataset.save_episode(episode_task=task)
        return
    except TypeError:
        pass
    dataset.save_episode()


def _finalize(dataset: Any) -> None:
    for attribute in ("finalize", "consolidate"):
        callable_attribute = getattr(dataset, attribute, None)
        if callable(callable_attribute):
            callable_attribute()
            return


def _write_sidecars(root: Path, *, repo_id: str, profile: Any) -> None:
    meta_dir = root / "meta"
    meta_dir.mkdir(parents=True, exist_ok=True)
    semantics = {
        "robot_profile": profile.profile_id,
        "profile_revision": profile.profile_revision,
        "state_units": profile.state_unit,
        "action_units": profile.action_unit,
        "action_semantics": profile.action_semantics,
        "joint_order": list(profile.joint_names),
        "data_origin": "synthetic",
        "evidence": (
            "synthetic V2 fixture generated by fixtures/v2/canonical_payloads.py with the "
            "official lerobot==0.4.4 Writer; joint positions in radians and action is the "
            "target joint position"
        ),
        "generator": "fixtures/v2/canonical_payloads.py",
        "seed": SEED,
    }
    source = {
        "repo_id": repo_id,
        "data_origin": "synthetic",
        "generator": "fixtures/v2/canonical_payloads.py",
        "seed": SEED,
        "notes": "synthetic fixture; not real robot capture",
    }
    for name, payload in (("dataops_semantics.json", semantics), ("dataops_source.json", source)):
        (meta_dir / name).write_text(
            json.dumps(payload, ensure_ascii=False, sort_keys=True, indent=2) + "\n",
            encoding="utf-8",
        )


def generate_lerobot_fixture(
    root: Path | str,
    *,
    profile: Any,
    cameras: dict[str, str],
    episodes: int = 1,
    frames: int = LEROBOT_FRAMES,
) -> Path:
    """Generate one deterministic LeRobot v3 dataset directory with the official Writer."""
    from embodied_dataops.imports.lerobot_v3 import lerobot_api_available

    if not lerobot_api_available():
        raise RuntimeError(
            "official lerobot==0.4.4 API is not importable; run `uv sync --extra lerobot`"
        )
    from lerobot.datasets.lerobot_dataset import LeRobotDataset

    root = Path(root)
    shutil.rmtree(root, ignore_errors=True)
    repo_id = f"dataops/{root.name}"
    dataset = _create_lerobot_dataset(
        LeRobotDataset,
        root=root,
        repo_id=repo_id,
        features=_lerobot_features(profile, cameras),
    )
    for episode in range(int(episodes)):
        for index in range(int(frames)):
            frame: dict[str, Any] = {
                key: _writer_image_value(
                    _camera_frame(
                        index, SEED + 100 + episode * 7 + camera_index, width=VIDEO_WIDTH, height=VIDEO_HEIGHT
                    )
                )
                for camera_index, key in enumerate(sorted(cameras.values()))
            }
            state = _joint_state(index, profile.state_dim, seed_offset=SEED % 97 + episode)
            frame["observation.state"] = __import__("torch").from_numpy(state.astype(np.float32))
            frame["action"] = __import__("torch").from_numpy(
                _robot_action(state).astype(np.float32)
            )
            frame["task"] = LEROBOT_TASK
            dataset.add_frame(frame)
        _save_episode(dataset, LEROBOT_TASK)
    _finalize(dataset)
    _write_sidecars(root, repo_id=repo_id, profile=profile)
    return root


