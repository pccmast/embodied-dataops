def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def directory_digest(path: Path) -> str:
    """Deterministic directory digest over relative paths + file SHA-256."""
    digest = hashlib.sha256()
    for child in sorted(Path(path).rglob("*")):
        if not child.is_file():
            continue
        digest.update(child.relative_to(path).as_posix().encode("utf-8"))
        digest.update(b"\0")
        digest.update(_sha256_file(child).encode("ascii"))
        digest.update(b"\n")
    return digest.hexdigest()


def directory_size(path: Path) -> int:
    return sum(child.stat().st_size for child in Path(path).rglob("*") if child.is_file())


